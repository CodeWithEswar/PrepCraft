  await page.goto("/preview")
  await expect(page.locator(".pc-shell")).toHaveAttribute("data-ready","true",{timeout:30000})
  await expect(page.getByRole("heading",{name:"Today",exact:true})).toBeVisible()
  for(const [width,height] of [[360,800],[390,844],[768,1024],[1024,768],[1440,900],[1920,1080]]) {
    await page.setViewportSize({width,height})
    await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    expect(await page.locator(".pc-shell-content, .pc-chamber").first().evaluate(node=>node.scrollWidth<=node.clientWidth)).toBe(true)
  }
  await page.setViewportSize({width:1536,height:960})
  await page.getByRole("button",{name:"Workspace color theme"}).click()
  await page.getByRole("menuitem",{name:"Light",exact:true}).click()
