  await page.evaluate(()=>document.fonts.ready)
  if(testInfo.project.name==="chromium") await page.screenshot({path:"docs/design/workspace/dashboard-light.png",style:"nextjs-portal{display:none!important}"})
  await page.getByRole("button",{name:"Collapse sidebar"}).click()
  await expect(page.locator(".pc-shell")).toHaveAttribute("data-collapsed","true")
  await page.getByRole("button",{name:"Expand sidebar"}).click()
  await page.getByRole("navigation",{name:"Workspace navigation",exact:true}).getByRole("link",{name:"Mistake journal",exact:true}).click()
