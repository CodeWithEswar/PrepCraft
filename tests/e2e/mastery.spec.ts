import { test,expect } from "@playwright/test"
test("Mastery Terrain selects evidence, supports keyboard movement, filters and explains gaps",async({page})=>{
 await page.setViewportSize({width:1536,height:1024})
 await page.goto("/preview/progress")
 await expect(page.locator(".pc-mastery")).toHaveAttribute("data-ready","true",{timeout:30000})
 await expect(page.getByRole("heading",{name:"Your Mastery Landscape",exact:true})).toBeVisible()
 await expect(page.getByText("Design preview · illustrative 90-day evidence · no mastery is saved.")).toBeVisible()
 const terrain=page.locator(".pc-mastery-terrain")
 await terrain.getByRole("button",{name:/Arrays Strong/}).click()
 await expect(page.locator(".pc-mastery-lens").getByRole("heading",{name:"Arrays",exact:true})).toBeVisible()
 await page.keyboard.press("ArrowRight")
 await expect(page.locator(".pc-mastery-lens").getByRole("heading",{name:"Strings",exact:true})).toBeVisible()
 await page.locator(".pc-mastery-lens").getByRole("button",{name:/Independent Solving/}).click()
 await expect(page.locator(".pc-mastery-lens").getByText(/5 of 6 initial attempts were independent/,{exact:false})).toBeVisible()
 await page.getByRole("textbox",{name:"Search mastery areas"}).fill("graphs")
 await expect(page.locator(".pc-mastery-rows>li")).toHaveCount(1)
 await page.getByRole("button",{name:"View evidence for Graphs",exact:true}).click()
 await page.locator(".pc-mastery-lens").getByRole("button",{name:"Weaknesses",exact:true}).click()
 await expect(page.locator(".pc-mastery-lens").getByText("No well-supported weakness has been found in this window.")).toBeVisible()
 await expect(page.locator(".pc-mastery-lens").getByRole("heading",{name:"Evidence Gaps",exact:true})).toBeVisible()
})
test("mobile Mastery puts action before Terrain and opens an Evidence Lens drawer",async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto("/preview/progress")
 await expect(page.locator(".pc-mastery")).toHaveAttribute("data-ready","true")
 const positions=await page.evaluate(()=>({action:document.querySelector(".pc-mastery-action")!.getBoundingClientRect().top,terrain:document.querySelector(".pc-mastery-terrain")!.getBoundingClientRect().top}))
 expect(positions.action).toBeLessThan(positions.terrain)
 await page.locator(".pc-mastery-terrain").getByRole("button",{name:/Sliding Window Developing/}).click()
 const lens=page.getByRole("dialog",{name:"Evidence Lens",exact:true})
 await expect(lens).toBeVisible()
 await expect(lens.getByRole("heading",{name:"Sliding Window",exact:true})).toBeVisible()
 await lens.getByRole("button",{name:"Evidence",exact:true}).click()
 await expect(lens.getByRole("heading",{name:"Evidence Spine",exact:true})).toBeVisible()
 await page.keyboard.press("Escape")
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
