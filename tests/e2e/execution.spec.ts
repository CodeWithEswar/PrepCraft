import {test,expect} from "@playwright/test"
test("execution preview keeps policies distinct, supports keyboard scrolling and mobile context",async({page})=>{
  test.setTimeout(90000)
  await page.emulateMedia({reducedMotion:"reduce"})
  await page.goto("/preview/practice")
  await expect(page.getByRole("heading",{name:"Longest substring without repeating characters",exact:true})).toBeVisible()
  await expect(page.getByRole("timer")).toHaveText(/--:--/)
  const modes=page.getByRole("navigation",{name:"Preview execution modes"})
  await modes.getByRole("button",{name:"Interview practice",exact:true}).click()
  await expect(page.locator(".pc-chamber")).toHaveAttribute("data-mode","interview")
  await expect(page.getByRole("button",{name:"Pause",exact:true})).toHaveCount(0)
  await expect(page.getByRole("button",{name:"Communication checklist"})).toBeVisible()
  await modes.getByRole("button",{name:"OA round",exact:true}).click()
  await expect(page.locator(".pc-chamber")).toHaveAttribute("data-mode","oa")
  await expect(page.getByRole("button",{name:"Pause",exact:true})).toHaveCount(0)
  await expect(page.getByRole("button",{name:/Reveal hint/})).toHaveCount(0)
  await page.setViewportSize({width:390,height:844})
  await page.locator(".pc-execution-mobile-controls").getByRole("button",{name:"Questions",exact:true}).click()
  await expect(page.getByRole("dialog",{name:"Round questions"})).toBeVisible()
  await page.getByRole("button",{name:/02 Find an insertion position/}).click()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("heading",{name:"Find an insertion position"})).toBeVisible()
  await page.getByRole("button",{name:"Working surface",exact:true}).click()
  await expect(page.getByRole("textbox",{name:"Code editor"})).toBeVisible()
  await expect(page.getByRole("button",{name:"Run",exact:true})).toBeDisabled()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
