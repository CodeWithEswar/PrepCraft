test("hero remains complete when WebGL is unavailable", async ({ browser }) => {
  const context = await browser.newContext({ viewport:{width:1440,height:900} })
  await context.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = function(this:HTMLCanvasElement, kind: string, ...args: unknown[]) {
      if (kind === "webgl" || kind === "webgl2" || kind === "experimental-webgl") return null
      return Reflect.apply(original,this,[kind,...args])
    } as typeof original
  })
  const page = await context.newPage()
  await page.goto("/")
  await expect(page.getByRole("heading", {level:1})).toBeVisible()
  await expect(page.locator(".pc-hero-artwork")).toBeVisible()
  await expect(page.locator("canvas")).toHaveCount(0)
  await expect(page.locator(".pc-hero-slide img").first()).toHaveJSProperty("complete",true)
  await page.getByRole("button", { name:"Start preparing",exact:true }).first().click()
  await expect(page.getByRole("dialog")).toBeVisible()
  await context.close()
})
