import { test,expect } from "@playwright/test"
test("Revision filters, evidence, history, horizon and policy",async({page})=>{
 await page.goto("/preview/revision")
 await expect(page.locator(".pc-revision")).toHaveAttribute("data-ready","true")
 await expect(page.getByRole("heading",{name:"Revision",exact:true})).toBeVisible()
 await expect(page.getByText("Design preview · illustrative evidence and dates · no reviews are saved.")).toBeVisible()
 await page.getByRole("button",{name:"Valid Parentheses Stack · easy",exact:true}).click()
 await expect(page.locator(".pc-revision-detail").getByRole("heading",{name:"Valid Parentheses",exact:true})).toBeVisible()
 await page.locator(".pc-revision-detail").getByRole("button",{name:"Review History",exact:true}).click()
 await expect(page.locator(".pc-revision-detail").getByRole("heading",{name:"Retention Thread",exact:true})).toBeVisible()
 await page.getByRole("textbox",{name:"Search revisions",exact:true}).fill("binary")
 await expect(page.locator(".pc-revision-row")).toHaveCount(1)
 await page.getByRole("button",{name:"Clear",exact:true}).click()
 await expect(page.locator(".pc-revision-row")).toHaveCount(8)
 await page.getByRole("button",{name:"Policy",exact:true}).click()
 await expect(page.getByRole("heading",{name:"A little distance. A lasting understanding."})).toBeVisible()
 await page.getByRole("button",{name:"Horizon",exact:true}).click()
 await page.getByRole("button",{name:"30 days",exact:true}).click()
 await expect(page.locator(".pc-horizon-column")).toHaveCount(30)
})
